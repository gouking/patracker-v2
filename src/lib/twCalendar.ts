// 台灣的上班日:週一到週五,扣掉國定假日(含補假)。
// 假日名單取自甘特圖「預設」地區的台灣假日;2026 年全年有,2027 年以後還沒建,暫時只扣週末
// (要補就在 TW_HOLIDAYS 加日期)。補班的週六不算上班日(圖表只是不畫假日,不影響任何計算)。

export const TW_HOLIDAYS: ReadonlySet<string> = new Set([
  "2026-01-01", // 元旦
  "2026-02-16", "2026-02-17", "2026-02-18", "2026-02-19", "2026-02-20", // 農曆春節(含補假)
  "2026-02-27", // 和平紀念日(補假)
  "2026-04-03", // 兒童節(補假)
  "2026-04-06", // 清明節(補假)
  "2026-05-01", // 勞動節
  "2026-06-19", // 端午節
  "2026-09-25", // 中秋節
  "2026-09-28", // 教師節
  "2026-10-09", // 國慶日(補假)
  "2026-10-26", // 光復節(補假)
  "2026-12-25", // 行憲紀念日
  "2027-01-01", // 元旦
]);

export function isTwWorkday(date: string): boolean {
  const dow = new Date(`${date}T00:00:00Z`).getUTCDay(); // 0 日 … 6 六
  return dow !== 0 && dow !== 6 && !TW_HOLIDAYS.has(date);
}
